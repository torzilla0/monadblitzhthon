/**
 * Writes src/lib/halka.ts from artifacts/Halka.json plus HALKA_ADDRESS in .env.
 * This file is the single source of truth the frontend imports. Regenerate it
 * after every deploy:  npx tsx scripts/gen-lib.ts
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();

export function genLib() {
  const artifact = JSON.parse(
    fs.readFileSync(path.join(ROOT, "artifacts", "Halka.json"), "utf8")
  );

  let address = "0x0000000000000000000000000000000000000000";
  const envPath = path.join(ROOT, ".env");
  if (fs.existsSync(envPath)) {
    const m = fs.readFileSync(envPath, "utf8").match(/^HALKA_ADDRESS=(0x[0-9a-fA-F]{40})/m);
    if (m) address = m[1];
  }

  const body = `// GENERATED by scripts/gen-lib.ts -- do not edit by hand.
// Regenerate with:  npx tsx scripts/gen-lib.ts
//
// This is the contract between backend and frontend. Frontend imports from here.

export { monadTestnet, RPC_URL } from "./chain";

export const HALKA_ADDRESS = "${address}" as const;

/** 0 = becayis post, 1 = room sticker */
export type ItemKind = 0 | 1;

export type Item = {
  id: number;
  owner: \`0x\${string}\`;
  kind: ItemKind;
  active: boolean;
  label: string;
};

export type Cycle = {
  /** item ids in cycle order: owner of items[i] receives items[i+1] */
  items: number[];
  participants: \`0x\${string}\`[];
  /** result of verifyTTCStep -- true means every participant got their top choice */
  isTopChoice: boolean;
};

/** GET /api/state?kind=0 */
export type StateResponse = {
  items: Item[];
  wants: Record<number, number[]>;
};

/** GET /api/cycles?kind=0 */
export type CyclesResponse = { cycles: Cycle[] };

/** POST /api/fund */
export type FundResponse = { ok: true; txHash: \`0x\${string}\` } | { ok: false; error: string };

export const HALKA_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;

  const out = path.join(ROOT, "src", "lib", "halka.ts");
  fs.writeFileSync(out, body);
  console.log(`-> src/lib/halka.ts   (address ${address})`);
  return address;
}

if (process.argv[1] && process.argv[1].endsWith("gen-lib.ts")) genLib();
